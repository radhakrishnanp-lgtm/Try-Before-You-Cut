// Generates supabase/seed.sql (global style catalogue) from src/lib/styles/catalogue.ts.
// Usage: npm run seed:sql
import { CATALOGUE } from "../src/lib/styles/catalogue.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = CATALOGUE.map(
  (s, i) =>
    `  (${q(s.id)}, null, ${q(s.name)}, ${q(s.gender)}, ${q(s.length)}, array[${s.textures.map(q).join(", ")}]::text[], ${q(s.description)}, ${q(s.prompt)}, ${q(JSON.stringify(s.art))}::jsonb, true, ${i})`,
);
console.log(`-- Generated by scripts/generate-seed.ts. Do not edit by hand.
insert into public.styles (id, salon_id, name, gender, length, textures, description, prompt, art, active, sort_order) values
${lines.join(",\n")}
on conflict (id) do update set
  name = excluded.name, gender = excluded.gender, length = excluded.length, textures = excluded.textures,
  description = excluded.description, prompt = excluded.prompt, art = excluded.art, sort_order = excluded.sort_order;`);
